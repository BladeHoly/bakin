def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def md_cell(text: str) -> str:
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


# ---------------------------------------------------------------- Rust ----

def rust_crates() -> list[dict]:
    raw = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", TARGET, "--manifest-path", str(TAURI / "Cargo.toml")],
        check=True, capture_output=True, text=True, encoding="utf-8").stdout
    meta = json.loads(raw)
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen: set[str] = set()
    stack = [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            kinds = {k["kind"] for k in dep["dep_kinds"]}
            if kinds - {"dev"}:  # normal (None) or build
                stack.append(dep["pkg"])
    seen.discard(root)
    crates = []
    for pid in seen:
        p = packages[pid]
        lic = p.get("license")
        if not lic and p.get("license_file"):
            lic = f"see {Path(p['license_file']).name} in the crate"
        crates.append({
            "name": p["name"], "version": p["version"],
            "license": lic or "UNKNOWN",
            "repository": p.get("repository") or p.get("homepage")
                          or f"https://crates.io/crates/{p['name']}",
        })
    crates.sort(key=lambda c: (c["name"].lower(), c["version"]))
    return crates


# -------------------------------------------------------------- Python ----

def py_license(dist: md.Distribution) -> str:
    m = dist.metadata
    expr = m.get("License-Expression")
    if expr:
        return expr.strip()
    classifiers = [c.split(" :: ")[-1] for c in m.get_all("Classifier") or []
                   if c.startswith("License :: ") and c != "License :: OSI Approved"]
    lic = (m.get("License") or "").strip()
    # Some packages put the whole license text in License: keep it short.
    if lic and len(lic) <= 80 and "\n" not in lic and lic.upper() != "UNKNOWN":
        return lic
    if classifiers:
        return " / ".join(dict.fromkeys(classifiers))
    if lic:
        return lic.splitlines()[0][:80]
    return "UNKNOWN"


def py_url(dist: md.Distribution) -> str:
    m = dist.metadata
    urls = {}
    for entry in m.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        urls[label.strip().lower()] = url.strip()
    for key in ("source", "source code", "repository", "code", "github", "homepage"):
        if key in urls:
            return urls[key]
    return m.get("Home-page") or (next(iter(urls.values())) if urls else "") \
        or f"https://pypi.org/project/{m['Name']}/"


def requirement_name(req: str) -> tuple[str, str]:
    """('name', 'marker') for a requirement string."""
    spec, _, marker = req.partition(";")
    name = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", spec).group(1)
    return name, marker.strip()


def marker_applies(marker: str) -> bool:
    """Evaluate a marker for the engine's platform (Windows, no extras)."""
    if not marker:
        return True
    if "extra" in marker:
        return False
    try:
        from packaging.markers import Marker
        return Marker(marker).evaluate({"sys_platform": "win32", "platform_system": "Windows",
                                        "os_name": "nt"})
    except Exception:
        return True  # be inclusive: a notice too many is harmless


def pyinstaller_collected() -> set[str]:
    """Distributions whose files PyInstaller put in the last engine build."""
    found: set[str] = set()
    tops: set[str] = set()
    for toc in ("PYZ-00.toc", "COLLECT-00.toc"):
        path = PYI_WORK / toc
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r"site-packages[\\/]+([A-Za-z0-9_.-]+)", text):
            top = m.group(1)
            if top.endswith(".dist-info"):
                found.add(norm(top.split("-")[0]))
            else:
                tops.add(top.split(".")[0])
    pkg_dists = md.packages_distributions()
    for top in tops:
        for d in pkg_dists.get(top, []):
            found.add(norm(d))
    return found


def python_packages() -> list[dict]:
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    pending = [requirement_name(r) for r in pyproject["project"]["dependencies"]]
    pending = [n for n, mk in pending if marker_applies(mk)]
    # What PyInstaller really collected is shipped, build tooling or not.
    collected = pyinstaller_collected() - {"bakin"}
    pending += sorted(collected)
    seen: dict[str, md.Distribution] = {}
    missing: list[str] = []
    while pending:
        name = norm(pending.pop())
        if name in seen or (name in PY_IGNORE and name not in collected):
            continue
        try:
            dist = md.distribution(name)
        except md.PackageNotFoundError:
            missing.append(name)
            continue
        seen[name] = dist
        for req in dist.requires or []:
            dep, marker = requirement_name(req)
            if marker_applies(marker):
                pending.append(dep)
    if missing:
        sys.exit(f"not installed in this interpreter: {', '.join(sorted(set(missing)))} "
                 "(run with the project's .venv after `pip install -e .`)")
    out = [{"name": d.metadata["Name"], "version": d.version,
            "license": py_license(d), "repository": py_url(d)} for d in seen.values()]
    out.sort(key=lambda p: p["name"].lower())
    return out


# --------------------------------------------------------------- write ----

def summary(rows: list[dict]) -> str:
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["license"]] = counts.get(r["license"], 0) + 1
    return ", ".join(f"{lic} ({n})" for lic, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def render(crates: list[dict], pys: list[dict]) -> str:
    lines = [HEADER]
    lines += ["## Summary", "",
              f"* Python packages ({len(pys)}): {summary(pys)}.",
              f"* Rust crates ({len(crates)}): {summary(crates)}.", ""]
    lines += ["## Python packages in the engine (`bakin-engine.exe`)", "",
              f"{len(pys)} packages.", "",
              "| Package | Version | License | Source |", "|---|---|---|---|"]
    lines += [f"| {md_cell(p['name'])} | {md_cell(p['version'])} | {md_cell(p['license'])} "
              f"| {md_cell(p['repository'])} |" for p in pys]
    lines += ["", f"## Rust crates in the desktop app (`{TARGET}`)", "",
              f"{len(crates)} crates.", "",
              "| Crate | Version | License | Repository |", "|---|---|---|---|"]
    lines += [f"| {md_cell(c['name'])} | {md_cell(c['version'])} | {md_cell(c['license'])} "
              f"| {md_cell(c['repository'])} |" for c in crates]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = render(rust_crates(), python_packages())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.name} is out of date: run packaging/notices.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"{OUT.name}: {len(text.splitlines())} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
