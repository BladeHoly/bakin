"""Generate THIRD-PARTY-NOTICES.md: every Rust crate in the Windows build and
every Python package frozen into bakin-engine.exe, with its license.

    .venv\\Scripts\\python packaging\\notices.py           # writes THIRD-PARTY-NOTICES.md
    .venv\\Scripts\\python packaging\\notices.py --check   # exits 1 if the file is out of date

Rust: `cargo metadata` filtered to x86_64-pc-windows-msvc, walking the
resolve graph from bakin-desktop through normal and build dependencies (dev
dependencies are left out: they are never compiled into the app).

Python: the runtime dependencies declared in pyproject.toml, resolved
transitively through the installed distributions (importlib.metadata) of the
interpreter that runs this script; plus, when a PyInstaller build exists in
build/pyinstaller, any other distribution PyInstaller actually collected
(hooks sometimes pull in optional imports).
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import json
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TAURI = ROOT / "desktop" / "src-tauri"
OUT = ROOT / "THIRD-PARTY-NOTICES.md"
TARGET = "x86_64-pc-windows-msvc"
PYI_WORK = ROOT / "build" / "pyinstaller" / "bakin-engine"

# Distributions that are build tooling, never part of the frozen engine.
PY_IGNORE = {"pip", "setuptools", "wheel", "pyinstaller", "pyinstaller-hooks-contrib",
             "altgraph", "pefile", "pywin32-ctypes", "packaging", "pytest", "pluggy",
             "iniconfig", "bakin"}

